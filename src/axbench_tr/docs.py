"""Generate ``DATA_SOURCES.md`` from the registry and the acquisition manifest.

Every number and hash in the generated file is read from ``registry.json`` and
``ACQUISITION.json``; nothing is typed by hand. ``python -m axbench_tr docs`` rewrites the file and
a test fails when the committed copy is stale.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .registry import ACQUISITION_PATH, REGISTRY_PATH

DATA_SOURCES_PATH = REGISTRY_PATH.parents[1] / "DATA_SOURCES.md"

STATUS_MEANING = {
    "accepted_adapted": "used: text adapted into labelled examples",
    "accepted_reference": "used: real observations or table headers (redistributable)",
    "accepted_schema_only": "used: column names and kinds only; observations not redistributed",
    "reviewed_not_used": "downloaded and reviewed; not used for training data",
    "blocked_access": "not acquired: access restricted or unavailable to automated clients",
    "probed_not_acquired": "probed; no machine-readable open data acquired in this pass",
}


LICENCE_EVIDENCE_PATH = REGISTRY_PATH.parent / "LICENCE_EVIDENCE.json"

