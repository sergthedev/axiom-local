def _mb(n: int) -> str:
    return f"{n / 1_000_000:.2f} MB"


def _status_meaning(status: str) -> str:
    return STATUS_MEANING.get(status, "rejected: see justification")


def render() -> str:
    registry = json.loads(REGISTRY_PATH.read_text("utf-8"))
    acquired = json.loads(ACQUISITION_PATH.read_text("utf-8"))["sources"]
    sources = registry["sources"]
    by_status = Counter(s["status"] for s in sources)
    lines = [
        "# AXBENCH-TR data sources",
        "",
        "Generated by `python -m axbench_tr docs` from "
        "`data/axbench-tr/sources/registry.json` and `ACQUISITION.json`. Do not edit by hand.",
        f"Access date: {registry['access_date']}. Sources surveyed: {len(sources)}. "
        f"Sources with downloaded files: {len(acquired)}.",
        "",
        "Raw downloads live outside Git (`data/axbench-tr/_raw/`, ignored) and are rebuilt with "
        "`python -m axbench_tr acquire`; `python -m axbench_tr verify` re-hashes them. "
        "Licence entries record what the cited page or card said on the access date; "
        "they are not legal advice and unverified terms are labelled so.",
        "",
        "## Decision summary",
        "",
        "| Status | Count | Meaning |",
        "| --- | ---: | --- |",
    ]
    for status, n in sorted(by_status.items()):
        lines.append(f"| `{status}` | {n} | {_status_meaning(status)} |")
    lines += ["", "## Per-source audit", ""]
    for s in sources:
        lic = s["license"]
        lic_id = lic["id"] if isinstance(lic, dict) else lic
        files = acquired.get(s["id"], {}).get("files", [])
        size = sum(f["bytes"] for f in files)
        lines += [
            f"### {s['id']} {s['name']}",
            "",
            f"- Publisher: {s['publisher']}",
            f"- URL: {s['url']}",
            f"- Revision: {s.get('revision') or 'not versioned by the publisher'}",
            f"- Licence: {lic_id}",
        ]
        if isinstance(lic, dict):
            lines += [
                f"  - Evidence: {lic.get('evidence', 'n/a')}",
                f"  - Derivative works: {lic.get('derivatives_allowed')}",
                f"  - Redistribution: {lic.get('redistribution', 'n/a')}",
            ]
        lines += [
            f"- Language: {', '.join(s['language'])}; domain: {s['domain']}",
            f"- Downloaded: {len(files)} files, {_mb(size)}" if files else "- Downloaded: none",
            f"- Decision: `{s['status']}` ({_status_meaning(s['status'])})",
            f"- Suitability: {s['suitability']}",
            f"- Justification: {s['justification']}",
            "",
        ]
    lines += [
        "## Derivative-data rights for what entered the corpus",
        "",
        "Summary for the reviewer. It is not legal advice and has not been reviewed by a lawyer.",
        "",
        "| Source | Licence | What was used | What it allows and asks |",
        "| --- | --- | --- | --- |",
    ]
    for row in DERIVATIVE_RIGHTS:
        lines.append("| " + " | ".join(row) + " |")
    if LICENCE_EVIDENCE_PATH.exists():
        evidence = json.loads(LICENCE_EVIDENCE_PATH.read_text("utf-8"))
        lines += [
            "",
            "## Licence evidence (pages and cards read)",
            "",
            f"Fetched {evidence['access_date']} by `python -m axbench_tr licences`; the hash "
            "identifies the bytes read.",
            "",
            "| Id | Sources | URL | SHA-256 | Excerpt |",
            "| --- | --- | --- | --- | --- |",
        ]
        for e in evidence["entries"]:
            excerpt = (e.get("excerpt") or e.get("status", "")).replace("|", "/")
            lines.append(
                f"| {e['id']} | {', '.join(e['sources'])} | {e['url']} | "
                f"`{e.get('sha256', 'n/a')}` | {excerpt} |"
            )
    lines += [
        "",
        "## Downloaded files (SHA-256)",
        "",
        "| Source | File | Bytes | SHA-256 | Retrieved |",
        "| --- | --- | ---: | --- | --- |",
    ]
    for sid, entry in sorted(acquired.items()):
        for f in entry["files"]:
            lines.append(
                f"| {sid} | `{Path(f['path']).as_posix()}` | {f['bytes']} | "
                f"`{f['sha256']}` | {f['retrieved']} |"
            )
    return "\n".join(lines) + "\n"


def write() -> Path:
    DATA_SOURCES_PATH.write_text(render(), encoding="utf-8", newline="\n")
    return DATA_SOURCES_PATH
