"""AXBENCH example generation (ADR 0011).

Order of operations, fixed before any example exists (DR-005):

1. families and schema instances are assigned to partitions (:mod:`axbench.families`);
2. request lineages are assigned to splits (:mod:`axbench.lineages`);
3. per split, exact counts are allocated to language, then stratum, then frame;
4. each example draws a lineage of its split and an instance of its stratum, fills the slots,
   renders the request (mentions, typos, diacritics, code-switching) and derives the gold
   candidate from the slot values (never from text);
5. exact duplicates (after normalization) anywhere in the corpus are regenerated.

The gold label is the canonical ``axiom.candidate/1`` object for the example's schema projection.
Generation is deterministic for a given seed. Synthetic examples are labelled as generated by the
implementing AI tool and unreviewed; nothing here is human-authored.
"""

from __future__ import annotations

import random
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from typing import Any

from axiom_router.contract import CANDIDATE_VERSION
from axiom_router.schema import deasciify, project_columns, turkish_lower

from .families import FAMILIES, FAMILY_BY_KEY, GENERIC, INSTANCES, Concept, SchemaInstance
from .lineages import FRAME_WEIGHTS, LINEAGES, Lineage, Split

CORPUS_VERSION = "axbench/0.1-draft"
GENERATOR_VERSION = "axbench.generate/0.1"
SPLITS: tuple[Split, ...] = ("train", "validation", "test")
TARGET_SIZES: dict[str, int] = {"train": 400, "validation": 160, "test": 360}
PILOT_SIZES: dict[str, int] = {"train": 200, "validation": 80, "test": 180}
LANGUAGE_SHARES = {"tr": 0.4, "en": 0.4, "mixed": 0.2}
STRATA: dict[str, dict[str, float]] = {
    "train": {"train": 1.0},
    "validation": {
        "A_heldout_family": 1 / 3,
        "B_novel_instance": 1 / 3,
        "C_familiar_instance": 1 / 3,
    },
    "test": {"A_heldout_family": 1 / 3, "B_novel_instance": 1 / 3, "C_familiar_instance": 1 / 3},
}
DEV_SEEDS = {
    "train": "axbench-0.1/train",
    "validation": "axbench-0.1/validation",
    "test": "axbench-0.1/test-dev-unsealed",  # only for audits; a sealed test uses the owner's seed
}

_TR_K = {2: "iki", 3: "üç", 4: "dört", 5: "beş", 6: "altı"}
_EN_K = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
_BAD_K = (1, 65, 80, 100, 250, 500)
_SLOT = re.compile(r"\{(\w+)\}")
_CONCEPTS = {(f.key, c.key): c for f in FAMILIES for c in f.concepts}


@dataclass(frozen=True, slots=True)
class Example:
    id: str
    split: str
    stratum: str
    language: str
    family: str
    domain: str
    schema_id: str
    lineage_id: str
    frame: str
    request: str
    schema: dict[str, Any]
    gold: dict[str, Any]
    tags: tuple[str, ...]
    seed_label: str

    def to_record(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "corpus_version": CORPUS_VERSION,
            "split": self.split,
            "stratum": self.stratum,
            "language": self.language,
            "family": self.family,
            "domain": self.domain,
            "schema_id": self.schema_id,
            "lineage_id": self.lineage_id,
            "frame": self.frame,
            "request": self.request,
            "schema": self.schema,
            "gold": self.gold,
            "accepted_variants": [],
            "tags": list(self.tags),
            "provenance": {
                "authoring": "ai_generated_from_templates",
                "generator": GENERATOR_VERSION,
                "seed_label": self.seed_label,
                "human_review": "none",
            },
        }


def normalize_request(text: str) -> str:
    """Duplicate key: case, diacritics, punctuation and spacing removed."""
    return " ".join(re.sub(r"[^0-9a-z]+", " ", deasciify(text)).split())


# --------------------------------------------------------------------------- allocation


def _largest_remainder(total: int, weights: dict[str, float]) -> dict[str, int]:
    norm = sum(weights.values())
    raw = {k: total * w / norm for k, w in weights.items()}
    out = {k: int(v) for k, v in raw.items()}
    rest = total - sum(out.values())
    for k in sorted(raw, key=lambda k: (-(raw[k] - out[k]), k))[:rest]:
        out[k] += 1
    return out


def _interleave(counts: dict[str, int]) -> list[str]:
    """Smooth weighted round robin: a sequence with exactly ``counts`` items, evenly spread."""
    total = sum(counts.values())
    current = dict.fromkeys(counts, 0)
    out = []
    for _ in range(total):
        for key, n in counts.items():
            current[key] += n
        best = max(sorted(current), key=lambda k: current[k])
        current[best] -= total
        out.append(best)
    return out


def allocate(split: str, total: int) -> list[tuple[str, str, str, int]]:
    """Exact (language, stratum, frame, count) cells.

    Frame, language and stratum totals are each exact (largest remainder). Frames are laid out in
    blocks and languages and strata are interleaved over them (cycle lengths 5 and 3), so every
    frame gets close to the target language and stratum mix. Independent of the seed.
    """
    frames = [f for f, n in _largest_remainder(total, FRAME_WEIGHTS).items() for _ in range(n)]
    langs = _interleave(_largest_remainder(total, LANGUAGE_SHARES))
    strata = _interleave(_largest_remainder(total, STRATA[split]))
    cells: dict[tuple[str, str, str], int] = {}
    for key in zip(langs, strata, frames, strict=True):
        cells[key] = cells.get(key, 0) + 1
    return [(lang, st, fr, n) for (lang, st, fr), n in cells.items()]


def instance_pool(split: str, stratum: str) -> list[SchemaInstance]:
    shared = {f.key for f in FAMILIES if f.partition == "shared"}
    if stratum in ("train", "C_familiar_instance"):
        return [i for i in INSTANCES if i.partition == "train"]
    if stratum == "B_novel_instance":
        return [i for i in INSTANCES if i.partition == split and i.family in shared]
    if stratum == "A_heldout_family":
        return [i for i in INSTANCES if i.partition == split and i.family not in shared]
    raise ValueError(stratum)


# --------------------------------------------------------------------------- rendering


def _typo(word_text: str, rng: random.Random) -> str | None:
    words = word_text.split(" ")
    cands = [i for i, w in enumerate(words) if len(w) >= 5 and w.isalpha()]
    if not cands:
        return None
    i = rng.choice(cands)
    w = words[i]
    j = rng.randrange(1, len(w) - 1)
    words[i] = (
        w[:j] + w[j + 1 :] if rng.random() < 0.5 else w[: j - 1] + w[j] + w[j - 1] + w[j + 1 :]
    )
    out = " ".join(words)
    return out if out != word_text else None


class _Renderer:
    def __init__(self, rng: random.Random, inst: SchemaInstance, lang: str, force_other: bool):
        self.rng = rng
        self.inst = inst
        self.lang = lang  # language of the template ("tr" or "en")
        self.other_pending = force_other
        self.tags: set[str] = set()

    def _phrase(self, concept: Concept, lang: str) -> str:
        return self.rng.choice(concept.tr_phrases if lang == "tr" else concept.en_phrases)

    def column(self, col_index: int) -> str:
        col = self.inst.columns[col_index]
        concept = _CONCEPTS[(self.inst.family, col.concept)]
        own = concept.tr_phrases if self.lang == "tr" else concept.en_phrases
        if self.other_pending:
            other = self._phrase(concept, "en" if self.lang == "tr" else "tr")
            if normalize_request(other) not in {normalize_request(p) for p in own}:
                self.other_pending = False
                self.tags.add("cross_language_mention")
                return other
        r = self.rng.random()
        if r < 0.35:
            name = col.name
            if " " in name or self.rng.random() < 0.3:
                self.tags.add("quoted_name")
                return f'"{name}"'
            return name
        phrase = self._phrase(concept, self.lang)
        if r < 0.45 and concept.generic and self._generic_unique(concept.generic):
            self.tags.add("generic_alias")
            return GENERIC[concept.generic][0 if self.lang == "tr" else 1]
        if r < 0.60 and self.lang == "tr" and deasciify(phrase) != turkish_lower(phrase):
            self.tags.add("diacritics_stripped")
            return deasciify(phrase)
        if r < 0.66:
            typo = _typo(phrase, self.rng)
            if typo:
                self.tags.add("typo")
                return typo
        if r < 0.75:
            self.tags.add("case_variant")
            return phrase.upper() if self.lang == "en" else phrase.capitalize()
        return phrase

    def _generic_unique(self, generic: str) -> bool:
        return len(self.generic_ids(generic)) == 1

    def generic_ids(self, generic: str) -> list[int]:
        out = []
        for i, col in enumerate(self.inst.columns):
            if col.concept and _CONCEPTS[(self.inst.family, col.concept)].generic == generic:
                out.append(i)
        return out

    def join(self, items: list[str]) -> str:
        last = " ve " if self.lang == "tr" else " and "
        return items[0] if len(items) == 1 else ", ".join(items[:-1]) + last + items[-1]

    def k_phrase(self, k: int, digits_only: bool) -> str:
        words = _TR_K if self.lang == "tr" else _EN_K
        if not digits_only and k in words and self.rng.random() < 0.35:
            self.tags.add("k_word")
            return words[k]
        return str(k)


def _absent_concept(inst: SchemaInstance, rng: random.Random) -> Concept | None:
    """A concept from another family whose words do not occur in any column of the instance."""
    inst_words = set()
    for col in inst.columns:
        inst_words |= set(normalize_request(col.name).split())
        if col.concept:
            c = _CONCEPTS[(inst.family, col.concept)]
            for p in (*c.tr_phrases, *c.en_phrases):
                inst_words |= set(normalize_request(p).split())
    pool = [
        c
        for f in FAMILIES
        if f.key != inst.family
        for c in f.concepts
        if c.kind == "numeric"
        and not any(
            len(w) >= 4 and w in inst_words
            for p in (*c.tr_phrases, *c.en_phrases)
            for w in normalize_request(p).split()
        )
    ]
    return rng.choice(pool) if pool else None


def _gold_ids(indices: Iterable[int]) -> list[str]:
    return [f"c{i + 1}" for i in indices]


def _fill(lineage: Lineage, inst: SchemaInstance, lang: str, mixed: bool, rng: random.Random):
    """Return (request, gold, tags, template_language) or None if the instance cannot host it."""
    if mixed and lineage.mix:
        template, tlang, force_other = lineage.mix, "tr", False
    elif mixed:
        tlang = rng.choice(("tr", "en"))
        template, force_other = (lineage.tr if tlang == "tr" else lineage.en), True
    else:
        template, tlang, force_other = (lineage.tr if lang == "tr" else lineage.en), lang, False
    slots = _SLOT.findall(template)
    col_slots = {"x", "y", "cols", "g", "v", "feats", "t", "gn", "a", "n"}
    if force_other and not (set(slots) & col_slots):
        return None
    usable = [i for i, c in enumerate(inst.columns) if c.concept]
    nums = [i for i in usable if inst.columns[i].kind == "numeric"]
    texts = [i for i in usable if inst.columns[i].kind == "text"]
    rng.shuffle(nums)
    rng.shuffle(texts)
    r = _Renderer(rng, inst, tlang, force_other)
    taken: set[int] = set()
    values: dict[str, Any] = {}

    def take(pool: list[int], n: int) -> list[int] | None:
        free = [i for i in pool if i not in taken]
        if len(free) < n:
            return None
        got = free[:n]
        taken.update(got)
        return got

    if "a" in slots:  # ambiguous generic group first, so other slots avoid it
        groups = [g for g in GENERIC if len(r.generic_ids(g)) >= 2]
        if not groups:
            return None
        generic = rng.choice(groups)
        ids = r.generic_ids(generic)
        taken.update(ids)
        values["a"] = ids
        r.tags.add("ambiguous_mention")
    order = ["g", "t", "gn", "x", "y", "v", "feats", "cols"]
    for slot in sorted(set(slots), key=lambda s: order.index(s) if s in order else 99):
        if slot in ("g", "t"):
            got = take(texts, 1)
        elif slot in ("x", "y", "v", "gn"):
            got = take(nums, 1)
        elif slot == "feats":
            got = take(nums, rng.choice((2, 2, 3)))
        elif slot == "cols":
            got = take([i for i in usable if i not in taken], rng.choice((1, 2, 2, 3)))
            if got:
                rng.shuffle(got)
        else:
            continue
        if got is None:
            return None
        values[slot] = got
    method = lineage.fixed.get("method") or rng.choice(("pearson", "spearman"))
    k = rng.choice((2, 3, 3, 4, 4, 5, 6))
    kbad = rng.choice(_BAD_K)
    absent = _absent_concept(inst, rng) if "n" in slots else None
    if "n" in slots and absent is None:
        return None

    text = template
    for slot in slots:
        if slot in ("x", "y", "g", "v", "t", "gn"):
            rep = r.column(values[slot][0])
        elif slot in ("cols", "feats"):
            rep = r.join([r.column(i) for i in values[slot]])
        elif slot == "a":
            use_tr = tlang == "tr"
            if r.other_pending:
                use_tr, r.other_pending = not use_tr, False
                r.tags.add("cross_language_mention")
            rep = GENERIC[generic][0 if use_tr else 1]
        elif slot == "n":
            use_tr = tlang == "tr"
            if r.other_pending:
                use_tr, r.other_pending = not use_tr, False
                r.tags.add("cross_language_mention")
            rep = rng.choice(absent.tr_phrases if use_tr else absent.en_phrases)
            r.tags.add("absent_column")
        elif slot == "m":
            rep = method.capitalize() if rng.random() < 0.8 else method
        elif slot == "k":
            rep = r.k_phrase(k, "k={k}" in template)
        elif slot == "kbad":
            rep = str(kbad)
        else:  # pragma: no cover - template error
            raise ValueError(slot)
        text = text.replace("{" + slot + "}", rep, 1)
    if force_other and r.other_pending:
        return None
    if r.tags & {"cross_language_mention"} and not mixed:
        return None
    gold = _gold(lineage, inst, values, method, k)
    tags = set(r.tags)
    if inst.malicious_header:
        tags.add("malicious_header")
    if lineage.frame == "reject:instruction_override":
        tags.add("request_injection")
    return text, gold, tuple(sorted(tags))


def _gold(
    lineage: Lineage, inst: SchemaInstance, values: dict[str, Any], method: str, k: int
) -> dict[str, Any]:
    head = {"version": CANDIDATE_VERSION}
    frame = lineage.frame
    if frame == "inspect":
        return {
            **head,
            "action": "PLAN",
            "operation": "inspect",
            "columns": _gold_ids(values["cols"]),
        }
    if frame == "inspect_all":
        return {
            **head,
            "action": "PLAN",
            "operation": "inspect",
            "columns": _gold_ids(range(len(inst.columns))),
        }
    if frame == "relate":
        return {
            **head,
            "action": "PLAN",
            "operation": "relate",
            "x": _gold_ids(values["x"])[0],
            "y": _gold_ids(values["y"])[0],
            "method": method,
        }
    if frame == "compare":
        return {
            **head,
            "action": "PLAN",
            "operation": "compare",
            "group_by": _gold_ids(values["g"])[0],
            "measure": _gold_ids(values["v"])[0],
        }
    if frame == "cluster":
        return {
            **head,
            "action": "PLAN",
            "operation": "cluster",
            "features": _gold_ids(values["feats"]),
            "k": k,
        }
    kind, reason = frame.split(":")
    if kind == "reject":
        return {**head, "action": "REJECT", "reason": reason}
    out: dict[str, Any] = {**head, "action": "CLARIFY", "reason": reason}
    if lineage.hint:
        out["operation"] = lineage.hint
    if reason == "ambiguous_column":
        out["columns"] = _gold_ids(sorted(values["a"]))
    return out


# --------------------------------------------------------------------------- splits


def _lineages(split: str, frame: str, extra: Sequence[Lineage] = ()) -> list[Lineage]:
    return [lin for lin in (*LINEAGES, *extra) if lin.split == split and lin.frame == frame]


def generate_split(
    split: str,
    *,
    seed: str | None = None,
    size: int | None = None,
    seen: set[str] | None = None,
    extra_lineages: Sequence[Lineage] = (),
) -> list[Example]:
    """Generate one split.

    ``seen`` holds normalized request texts of other splits; a text in it is never reused (no
    exact cross-split duplicates). Within the split, the duplicate key is (text, schema instance):
    a column-free request such as "Summarize every column" may recur with different schemas,
    which can change its gold label. Repetition is reported by the audit. ``seen`` is updated.
    """
    seed = seed if seed is not None else DEV_SEEDS[split]
    total = size if size is not None else TARGET_SIZES[split]
    rng = random.Random(f"{GENERATOR_VERSION}|{split}|{seed}")
    seen = seen if seen is not None else set()
    local: set[tuple[str, str]] = set()
    examples: list[Example] = []
    for lang, stratum, frame, count in allocate(split, total):
        pool = instance_pool(split, stratum)
        lineages = _lineages(split, frame, extra_lineages)
        if not lineages:
            raise RuntimeError(f"no {split} lineage for frame {frame}")
        made = 0
        attempts = 0
        while made < count:
            attempts += 1
            if attempts > 2_000:
                raise RuntimeError(f"cannot fill {split}/{lang}/{stratum}/{frame}")
            lineage = (
                lineages[(made + attempts) % len(lineages)]
                if attempts % 3
                else rng.choice(lineages)
            )
            inst = rng.choice(pool)
            filled = _fill(lineage, inst, lang, lang == "mixed", rng)
            if filled is None:
                continue
            request, gold, tags = filled
            key = normalize_request(request)
            if key in seen or (key, inst.id) in local:
                continue
            local.add((key, inst.id))
            examples.append(
                Example(
                    id="",
                    split=split,
                    stratum=stratum,
                    language=lang,
                    family=inst.family,
                    domain=FAMILY_BY_KEY[inst.family].domain,
                    schema_id=inst.id,
                    lineage_id=lineage.id,
                    frame=frame,
                    request=request,
                    schema=project_columns(
                        [(c.name, c.kind) for c in inst.columns]
                    ).to_prompt_payload(),
                    gold=gold,
                    tags=tags,
                    seed_label="owner_secret"
                    if split == "test" and seed != DEV_SEEDS["test"]
                    else seed,
                )
            )
            made += 1
    rng.shuffle(examples)
    seen.update(normalize_request(e.request) for e in examples)
    return [Example(**{**_fields(e), "id": f"{split}-{i + 1:04d}"}) for i, e in enumerate(examples)]


def _fields(e: Example) -> dict[str, Any]:
    return {f: getattr(e, f) for f in Example.__dataclass_fields__}


def generate_development_corpus(sizes: dict[str, int] | None = None) -> dict[str, list[Example]]:
    """Train and validation with the development seeds (the committed draft corpus)."""
    sizes = sizes or TARGET_SIZES
    seen: set[str] = set()
    return {s: generate_split(s, size=sizes[s], seen=seen) for s in ("train", "validation")}


def generate_all_for_audit(
    test_seed: str | None = None, sizes: dict[str, int] | None = None
) -> dict[str, list[Example]]:
    """All three splits in memory (for the leakage audit and tests only; never written in-repo)."""
    sizes = sizes or TARGET_SIZES
    corpus = generate_development_corpus(sizes)
    seen = {normalize_request(e.request) for exs in corpus.values() for e in exs}
    corpus["test"] = generate_split("test", seed=test_seed, size=sizes["test"], seen=seen)
    return corpus
